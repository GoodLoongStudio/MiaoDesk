import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cpp = await readFile(join(here, '..', 'src', 'ai', 'pi', 'PiNativeToolsExtension.cpp'), 'utf8');
const match = /kExtensionSourcePart1 = R"PIEXT\(([\s\S]*?)\)PIEXT";/.exec(cpp);
if (!match) throw new Error('kExtensionSourcePart1 not found');
const source = match[1];

function between(startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  if (start < 0) throw new Error('marker not found: ' + startMarker);
  const end = source.indexOf(endMarker, start);
  if (end < 0) throw new Error('end marker not found: ' + endMarker);
  return source.slice(start, end);
}

const constants = between('const IMAGE_PROVIDER', 'const TOOL_NAMES');
const baseUrl = between('async function currentMiaoDeskBaseUrl', '// Resolves the credential');
const key = between('// Resolves the credential', 'function usesOpenAICompatibleImageShim');
let shim = between('function usesOpenAICompatibleImageShim', 'async function generateImage');
shim = shim
  .replace('function usesOpenAICompatibleImageShim(provider: string): boolean',
           'function usesOpenAICompatibleImageShim(provider)')
  .replace('function openAIImageEndpoint(baseUrl: string): string',
           'function openAIImageEndpoint(baseUrl)')
  .replace('  prompt: string, imageModel: string, apiKey: string, signal?: AbortSignal',
           '  prompt, imageModel, apiKey, signal')
  .replace('): Promise<{ data: string; mimeType: string }>', ')')
  .replace('  const headers: Record<string, string> = { "Content-Type": "application/json" };',
           '  const headers = { "Content-Type": "application/json" };')
  .replace('  let body: any = {};',
           '  let body = {};');

const module = `// GENERATED by extract-image-openai-shim.mjs — do not edit.
import { readFile } from "node:fs/promises";
import { join } from "node:path";
${constants}
${baseUrl}
${key}
${shim}
export { IMAGE_PROVIDER, IMAGE_BASE_URL, IMAGE_MODEL, isLoopback,
         resolveImageApiKey, usesOpenAICompatibleImageShim,
         openAIImageEndpoint, generateOpenAICompatibleImage };
`;

const target = join(here, 'extracted-image-openai-shim.mjs');
await writeFile(target, module, 'utf8');
export default target;
