#!/usr/bin/env python3
"""Generate the missing artwork for NeonCity.mdwall and MysticMoon.mdwall.

Why this exists, and why it is not "inventing the visuals"
----------------------------------------------------------
Both packages declare five image layers in scene.ini, each with a filename, a
placement, an opacity and an animation. Neither package has ever contained those
files: git has no record of them and the names appear nowhere else in the tree.
The consequence is not "the art looks wrong" — it is that `DrawLayer` starts with
`if (!layer.bitmap) return;`, so every layer is skipped and the wallpaper draws
nothing at all, silently. That is the same silent failure the content rules exist
to prevent, and no amount of renderer work closes it.

So the composition was never the open question. `scene.ini` already decides it:
five layers, back to front, at named boxes and opacities. What is missing is the
pixel content of five files, and this script produces it.

What that means, stated plainly so nobody has to reverse-engineer it later:

  * The **composition** is scene.ini's. Layer order, boxes, opacities, animation
    parameters and the fact that a layer is a skyline rather than a portrait all
    come from the .ini; nothing here reinterprets them.
  * The **pixels** are synthetic. A human art pass can replace any file with real
    art and nothing else changes — scene.json references these files by name, and
    the renderer scales each bitmap to the layer box.
  * Everything is **seeded per package and per layer**, so regenerating produces
    byte-identical output. That is what makes this a reviewed, reproducible input
    rather than a one-off drop: `--check` re-renders and compares checksums.
  * No third-party material is involved, which matters for the asset-licence
    question (P0-5): these are generated by the project itself.

Output sizes are each layer's own box from scene.ini, so the renderer's
scale-to-rect is a no-op and the art is never resampled.

Run:  python3 scripts/generate-builtin-wallpaper-art.py [--write] [--check]
"""
