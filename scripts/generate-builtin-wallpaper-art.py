NEON_WINDOWS = [(53, 240, 224), (255, 63, 176), (255, 194, 74), (108, 255, 178)]
NEON_BODIES = [(11, 13, 24), (16, 16, 32), (8, 10, 20), (20, 18, 38)]


def neon_city_background(width, height, rng):
    surface = Surface(width, height)
    skyline(surface, rng, horizon=height * 0.86, palette=NEON_BODIES,
            window_palette=NEON_WINDOWS)
    return surface


def neon_city_glow(width, height, rng):
    """The lit skyline itself, with bloom, and a magenta wash above the roofs."""
    surface = Surface(width, height)
    horizon = height * 0.84
    x = -rng.randint(0, 40)
    while x < width:
        building_w = rng.randint(52, 124)
        building_h = rng.randint(int(horizon * 0.16), int(horizon * 0.92))
        top = horizon - building_h
        silhouette = bytes((9, 11, 22, 255))
        for yy in range(int(top), height):
            row = yy * width * 4
            x0, x1 = max(0, x), min(width, x + building_w)
            surface.px[row + x0 * 4:row + x1 * 4] = silhouette * (x1 - x0)
        cell_w, cell_h = 9, 13
        for wy in range(int(top) + 8, height - 6, cell_h):
            for wx in range(x + 6, x + building_w - 6, cell_w):
                if rng.random() > 0.40:
                    continue
                colour = rng.choice(NEON_WINDOWS)
                dim = rng.uniform(0.45, 1.0)
                lit = tuple(int(c * dim) for c in colour)
                for dy in range(min(5, cell_h - 4)):
                    for dx in range(min(4, cell_w - 3)):
                        surface.blend(wx + dx, wy + dy, *lit, 238)
        x += building_w + rng.randint(2, 10)
    surface.bloom(scale=5, strength=0.85)
    # Neon bounce light on the "wet street" band at the very bottom.
    for y in range(int(height * 0.94), height):
        for x2 in range(width):
            surface.blend(x2, y, 48, 120, 190, 26)
    return surface


def neon_haze(width, height, rng):
    surface = Surface(width, height)
    soft_bands(surface, rng, bands=5, colour=(196, 96, 190), alpha=46,
               y_range=(height * 0.55, height * 0.92), height_scale=(26, 74))
    return surface


def neon_rain(width, height, rng, near):
    surface = Surface(width, height)
    if near:
        rain(surface, rng, count=1500, length=96, alpha=132, thickness=2,
             tint=(196, 220, 255))
    else:
        rain(surface, rng, count=700, length=54, alpha=62, thickness=1,
             tint=(150, 176, 226))
    return surface


def mystic_background(width, height, rng):
    surface = Surface(width, height)
    surface.fill_gradient((6, 9, 24), (14, 22, 46))
    stars(surface, rng, count=420)
    return surface


def mystic_moon(width, height, rng):
    surface = Surface(width, height)
    moon(surface, cx=width * 0.66, cy=height * 0.24, radius=height * 0.105)
    return surface


def mystic_water(width, height, rng):
    surface = Surface(width, height)
    # Shimmer: horizontal bands whose brightness wobbles on a slow sine, so the
    # water reads as moving without any per-pixel noise to alias.
    for y in range(int(height * 0.60), height):
        depth = (y - height * 0.60) / (height * 0.40)
        for x in range(width):
            wave = (math.sin(x * 0.021 + y * 0.10) * 0.5 + 0.5) * \
                   (math.sin(y * 0.42) * 0.5 + 0.5)
            alpha = int(64 * (0.25 + 0.75 * wave) * (0.35 + 0.65 * depth))
            surface.blend(x, y, 120, 168, 226, alpha)
    return surface


def mystic_fog(width, height, rng):
    surface = Surface(width, height)
    soft_bands(surface, rng, bands=7, colour=(206, 216, 240), alpha=40,
               y_range=(height * 0.52, height * 0.95), height_scale=(34, 88))
    return surface


def mystic_fireflies(width, height, rng):
    surface = Surface(width, height)
    fireflies(surface, rng, count=110)
    return surface


