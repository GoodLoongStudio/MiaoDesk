def skyline(surface, rng, horizon, palette, window_palette):
    """Buildings from the bottom up to `horizon`, with lit windows.

    The silhouette is deliberately near-black rather than dark blue: the neon
    already carries the colour, and a tinted silhouette muddies it. Windows are
    what the package is named for, so they get the detail budget.
    """
    surface.fill_gradient((10, 13, 28), (26, 22, 48))
    x = -rng.randint(0, 40)
    while x < surface.width:
        width = rng.randint(46, 118)
        height = rng.randint(int(horizon * 0.18), int(horizon * 0.95))
        # int() here, not at each use: `top` feeds range() in two places and a float
        # in range() is a TypeError, while a rounded int used consistently is the same
        # pixels either way.
        top = int(horizon - height)
        body = rng.choice(palette)
        for yy in range(int(top), surface.height):
            row = yy * surface.width * 4
            shade = 1.0 - (yy - int(top)) / max(1, height) * 0.25
            colour = bytes((int(body[0] * shade), int(body[1] * shade),
                            int(body[2] * shade), 255))
            x0, x1 = max(0, x), min(surface.width, x + width)
            surface.px[row + x0 * 4:row + x1 * 4] = colour * (x1 - x0)
        # Windows on a grid with random occupancy; taller buildings get more rows.
        cell_w, cell_h = 9, 13
        for wy in range(top + 8, surface.height - 6, cell_h):
            for wx in range(x + 6, x + width - 6, cell_w):
                if rng.random() > 0.42:
                    continue
                colour = rng.choice(window_palette)
                dim = rng.uniform(0.45, 1.0)
                lit = tuple(int(c * dim) for c in colour)
                for dy in range(min(5, cell_h - 4)):
                    for dx in range(min(4, cell_w - 3)):
                        surface.blend(wx + dx, wy + dy, *lit, 235)
        x += width + rng.randint(2, 10)
    surface.bloom(scale=6, strength=0.6)
    # A low warm haze so the lower buildings read as further away.
    for y in range(int(horizon * 0.82), surface.height):
        t = (y - int(horizon * 0.82)) / max(1, surface.height - int(horizon * 0.82))
        alpha = int(70 * t)
        for x2 in range(surface.width):
            surface.blend(x2, y, 90, 60, 130, alpha)


def rain(surface, rng, count, length, alpha, thickness, tint):
    """Diagonal streaks. Length and alpha are what separate near from far rain;
    count is the other half, and both are seeded so the two layers differ but
    neither drifts between regenerations."""
    for _ in range(count):
        x = rng.uniform(-length, surface.width + length)
        y = rng.uniform(-length, surface.height)
        speed = rng.uniform(0.8, 1.25)
        steps = int(length * speed)
        for s in range(steps):
            t = s / max(1, steps - 1)
            fade = math.sin(t * math.pi)  # streaks taper at both ends
            a = int(alpha * fade)
            if thickness <= 1:
                surface.blend(int(x + s * 0.22), int(y + s), *tint, a)
            else:
                for k in range(thickness):
                    surface.blend(int(x + s * 0.22) + k, int(y + s), *tint, a)


def soft_bands(surface, rng, bands, colour, alpha, y_range, height_scale):
    """Horizontal soft bands — haze over a skyline, fog over a field, shimmer on
    water. One shape, three uses, because all three are 'a wide, low, blurred
    smear' and writing three nearly identical blurs would be three chances to
    drift apart."""
    top, bottom = y_range
    for _ in range(bands):
        cy = rng.uniform(top, bottom)
        half_h = rng.uniform(*height_scale)
        for y in range(max(0, int(cy - half_h)), min(surface.height, int(cy + half_h) + 1)):
            t = (y - cy) / half_h
            vertical = max(0.0, 1.0 - t * t)
            for x in range(surface.width):
                # A slow horizontal wobble keeps the band from reading as a
                # machine-drawn rectangle.
                wobble = 0.72 + 0.28 * math.sin(x * 0.006 + cy * 0.35 + rng.random() * 0.0)
                a = int(alpha * vertical * vertical * wobble)
                surface.blend(x, y, *colour, a)


def fireflies(surface, rng, count):
    for _ in range(count):
        x = rng.uniform(0, surface.width)
        y = rng.uniform(surface.height * 0.35, surface.height * 0.97)
        radius = rng.uniform(6, 17)
        warmth = rng.uniform(0.75, 1.0)
        colour = (int(255 * warmth), int(214 * warmth), int(120 * warmth))
        surface.radial(x, y, radius, colour, rng.uniform(0.35, 1.0))
        surface.blend(int(x), int(y), 255, 246, 214, 255)


def moon(surface, cx, cy, radius):
    """Disc, craters, halo. The halo is drawn first so the disc stays crisp."""
    surface.radial(cx, cy, radius * 6.0, (150, 170, 220), 0.5)
    surface.radial(cx, cy, radius * 2.6, (200, 214, 245), 0.7)
    for y in range(int(cy - radius), int(cy + radius) + 1):
        for x in range(int(cx - radius), int(cx + radius) + 1):
            dx, dy = x - cx, y - cy
            if dx * dx + dy * dy > radius * radius:
                continue
            shade = 1.0 - 0.12 * ((dx + dy) / (2 * radius) + 0.5)
            surface.blend(x, y, int(246 * shade), int(240 * shade), int(214 * shade), 255)
    # Craters: fixed offsets, so re-rendering does not move them.
    for ox, oy, r in ((-0.22, -0.16, 0.19), (0.16, 0.22, 0.13), (0.30, -0.30, 0.10)):
        ccx, ccy = cx + ox * radius, cy + oy * radius
        cr = r * radius
        for y in range(int(ccy - cr), int(ccy + cr) + 1):
            for x in range(int(ccx - cr), int(ccx + cr) + 1):
                dx, dy = x - ccx, y - ccy
                if dx * dx + dy * dy > cr * cr:
                    continue
                surface.blend(x, y, 206, 198, 176, 120)


def stars(surface, rng, count):
    for _ in range(count):
        x = rng.uniform(0, surface.width)
        y = rng.uniform(0, surface.height * 0.7)
        brightness = rng.uniform(0.25, 1.0)
        radius = rng.uniform(0.6, 1.7)
        surface.radial(x, y, radius * 2.4, (235, 238, 255),
                       brightness * rng.uniform(0.5, 1.0))
        surface.blend(int(x), int(y), 245, 248, 255, int(230 * brightness))


