// Extracts the image-provider decision logic out of the shipped extension source,
// so tests/image-provider.mjs runs the real bytes instead of a hand-copied duplicate.
//
// The extension lives in a C++ raw string literal (kExtensionSourcePart1 inside
// src/ai/pi/PiNativeToolsExtension.cpp) and is written to disk at runtime. There is
// no separate .ts file to import, so extraction is the only way to exercise it
// directly. If the naming or structure of that source changes, this fails loudly
// rather than silently testing nothing.
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const extensionCpp = join(here, '..', 'src', 'ai', 'pi', 'PiNativeToolsExtension.cpp');

const cpp = await readFile(extensionCpp, 'utf8');
const match = /kExtensionSourcePart1 = R"PIEXT\(([\s\S]*?)\)PIEXT";/.exec(cpp);
if (!match) {
  throw new Error('kExtensionSourcePart1 not found in PiNativeToolsExtension.cpp');
}
const source = match[1];

function between(startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  if (start < 0) throw new Error(`marker not found: ${startMarker}`);
  const end = source.indexOf(endMarker, start);
  if (end < 0) throw new Error(`end marker not found: ${endMarker}`);
  return source.slice(start, end);
}

const constants = between('const IMAGE_PROVIDER', 'const TOOL_NAMES');
const baseUrl = between('async function currentMiaoDeskBaseUrl', '// Resolves the credential');
const keyResolution = between('// Resolves the credential', 'async function generateImage');

let generateImage = between('async function generateImage', 'const result = await generateImages');
generateImage = generateImage.replace(
  'const { getImageModel, generateImages } = await import("@earendil-works/pi-ai/compat");',
  'const { getImageModel } = await import("./stub-get-image-model.mjs");'
);
// The real function continues into an HTTP call against a provider that is not
// installed here. Truncate at the model-resolution point, which is exactly the
// decision under test, and leave the function syntactically complete.
generateImage = generateImage.trimEnd() +
  '\n  throw new Error("STUB: provider/model decision reached, real HTTP not exercised");\n}\n';

const module = `// GENERATED by extract-image-provider.mjs — do not edit.
//
// Imports are added here because the extracted functions reference them and the
// C++ raw string they came from does not carry them. Omitting these makes
// currentMiaoDeskBaseUrl swallow a ReferenceError in its catch and return "", which
// looks exactly like "no profile configured" — a silent failure that reads as a
// product bug.
import { readFile } from "node:fs/promises";
import { join } from "node:path";

${constants}
${baseUrl}
${keyResolution}
${generateImage}
const DEFAULT_IMAGE_MODEL = "google/gemini-2.5-flash-image";
export { currentMiaoDeskBaseUrl, resolveImageApiKey, generateImage,
         IMAGE_PROVIDER, IMAGE_MODEL, DEFAULT_IMAGE_MODEL, isLoopback };
`;

// .mts rather than .ts: Node decides whether a stripped .ts file is ESM or CJS from
// the nearest package.json "type" field (this repo has none for tests/), and that
// decision is what made this gate platform- and Node-version-sensitive. .mts is
// unambiguously ESM, so the extracted module — which uses export/import — resolves
// the same way everywhere.
const target = join(here, 'extracted-image-provider.mts');
await writeFile(target, module, 'utf8');
export default target;
