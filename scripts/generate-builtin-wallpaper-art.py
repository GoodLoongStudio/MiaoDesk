def write_png(path, width, height, rgba):
    """Write an 8-bit RGBA PNG. Straight alpha, no interlacing."""
    raw = bytearray()
    stride = width * 4
    for y in range(height):
        raw.append(0)  # filter type 0: None. Per-row filters would buy a few
        # percent on gradients and cost a real dependency; zlib already handles
        # the long runs these images are made of.
        raw += rgba[y * stride:(y + 1) * stride]
    compressed = zlib.compress(bytes(raw), 9)

    def chunk(tag, data):
        return (struct.pack(">I", len(data)) + tag + data +
                struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    blob = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) +
            chunk(b"IDAT", compressed) + chunk(b"IEND", b""))
    path.write_bytes(blob)


def write_jpeg(path, width, height, rgb, quality=88):
    """Encode an 8-bit RGB JPEG.

    PIL when it is installed, otherwise `sips` on macOS. Neither is a gate
    dependency — this is a content-generation tool a human runs, and the image it
    writes is committed. The output is verified below by decoding it again, so a
    converter that silently produced something else cannot pass unnoticed.
    """
    try:
        from PIL import Image  # type: ignore
        image = Image.frombytes("RGB", (width, height), bytes(rgb))
        image.save(path, "JPEG", quality=quality, subsampling=0, optimize=True)
        return "PIL"
    except ImportError:
        pass
    png = path.with_suffix(".tmp.png")
    write_png(png, width, height, _rgb_to_rgba(rgb))
    import subprocess
    result = subprocess.run(
        ["sips", "-s", "format", "jpeg", "-s", "formatOptions", str(quality),
         str(png), "--out", str(path)],
        capture_output=True, text=True)
    png.unlink(missing_ok=True)
    if result.returncode != 0 or not path.exists():
        raise SystemExit(
            "❌ 写不出 JPEG:既没有 PIL,macosOS 的 sips 也失败了。\n%s" % result.stderr)
    return "sips"


def _rgb_to_rgba(rgb):
    rgba = bytearray(len(rgb) // 3 * 4)
    for i in range(len(rgb) // 3):
        rgba[i * 4:i * 4 + 3] = rgb[i * 3:i * 3 + 3]
        rgba[i * 4 + 3] = 0xFF
    return rgba


def read_png_size(path):
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    w, h = struct.unpack(">II", data[16:24])
    return w, h


def read_jpeg_size(path):
    data = path.read_bytes()
    i = 2
    while i < len(data) - 9:
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        if marker in (0xC0, 0xC1, 0xC2, 0xC3):
            h, w = struct.unpack(">HH", data[i + 5:i + 9])
            return w, h
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        i += 2 + length
    return None


# ---------------------------------------------------------------------------
# A small straight-alpha raster surface
# ---------------------------------------------------------------------------
class Surface:
    def __init__(self, width, height):
        self.width = width
        self.height = height
        self.px = bytearray(width * height * 4)  # transparent black

    def blend(self, x, y, r, g, b, a):
        """Source-over one pixel, a in 0..255."""
        if x < 0 or y < 0 or x >= self.width or y >= self.height:
            return
        i = (y * self.width + x) * 4
        if a <= 0:
            return
        if a >= 255:
            self.px[i:i + 4] = bytes((int(r), int(g), int(b), 255))
            return
        sa = a / 255.0
        da = self.px[i + 3] / 255.0
        out_a = sa + da * (1 - sa)
        if out_a <= 0:
            return
        for c, value in enumerate((r, g, b)):
            src = value / 255.0
            dst = self.px[i + c] / 255.0
            self.px[i + c] = int(round(255 * (src * sa + dst * da * (1 - sa)) / out_a))
        self.px[i + 3] = int(round(255 * out_a))

    def fill_gradient(self, top, bottom):
        # One slice assignment per row. The per-pixel version of this was the
        # difference between a few seconds and a few minutes on a 1672x941 image,
        # and it is the kind of thing nobody notices until they regenerate.
        for y in range(self.height):
            t = y / max(1, self.height - 1)
            colour = bytes(int(round(top[c] + (bottom[c] - top[c]) * t)) for c in range(3))
            row = colour + b"\xff"
            base = y * self.width * 4
            self.px[base:base + self.width * 4] = row * self.width

    def radial(self, cx, cy, radius, colour, strength):
        """Add a soft additive halo. Ignored where it is fully transparent."""
        x0, x1 = max(0, int(cx - radius)), min(self.width, int(cx + radius) + 1)
        y0, y1 = max(0, int(cy - radius)), min(self.height, int(cy + radius) + 1)
        for y in range(y0, y1):
            dy = (y + 0.5 - cy) / radius
            for x in range(x0, x1):
                dx = (x + 0.5 - cx) / radius
                d2 = dx * dx + dy * dy
                if d2 >= 1.0:
                    continue
                falloff = (1.0 - d2) ** 2
                i = (y * self.width + x) * 4
                for c in range(3):
                    self.px[i + c] = min(255, int(self.px[i + c] + colour[c] * falloff * strength))

    def bloom(self, scale=6, strength=0.55):
        """Cheap glow: box-blur a downsampled copy and add it back.

        The alternative — a halo per light source — is O(lights x pixels) and
        these images have hundreds of windows. Downsample + blur + upsample is
        how every cheap bloom works and it is visually indistinguishable here.
        """
        w, h = self.width // scale, self.height // scale
        if w < 2 or h < 2:
            return
        stride = self.width * 4
        small = [[[0.0, 0.0, 0.0] for _ in range(w)] for _ in range(h)]
        for y in range(h):
            for x in range(w):
                acc = [0.0, 0.0, 0.0]
                for sy in range(scale):
                    for sx in range(scale):
                        i = ((y * scale + sy) * self.width + (x * scale + sx)) * 4
                        if self.px[i + 3] < 8:
                            continue
                        for c in range(3):
                            acc[c] += self.px[i + c]
                n = scale * scale
                for c in range(3):
                    small[y][x][c] = acc[c] / n
        blurred = _box_blur(small, w, h, 2)
        for y in range(h):
            for x in range(w):
                bx, by = x * scale, y * scale
                for sy in range(scale):
                    for sx in range(scale):
                        px, py = bx + sx, by + sy
                        if px >= self.width or py >= self.height:
                            continue
                        i = (py * self.width + px) * 4
                        # Bilinear between the blurred samples: nearest-neighbour
                        # upsampling makes the glow visibly blocky at this size.
                        fx = (px - bx) / scale
                        fy = (py - by) / scale
                        sample = _bilinear(blurred, w, h, x + fx, y + fy)
                        for c in range(3):
                            self.px[i + c] = min(
                                255, int(self.px[i + c] + sample[c] * strength))
        del stride

    def to_rgb(self):
        """Flatten to opaque RGB — what a JPEG background needs."""
        out = bytearray(self.width * self.height * 3)
        for i in range(self.width * self.height):
            a = self.px[i * 4 + 3]
            if a >= 255:
                out[i * 3:i * 3 + 3] = self.px[i * 4:i * 4 + 3]
            elif a == 0:
                out[i * 3:i * 3 + 3] = b"\x00\x00\x00"
            else:
                for c in range(3):
                    out[i * 3 + c] = int(self.px[i * 4 + c] * a / 255)
        return out


def _box_blur(grid, w, h, radius):
    out = [[list(grid[y][x]) for x in range(w)] for y in range(h)]
    for _ in range(radius):
        tmp = [[[0.0, 0.0, 0.0] for _ in range(w)] for y in range(h)]
        for y in range(h):
            for x in range(w):
                acc = [0.0, 0.0, 0.0]
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        xx, yy = min(w - 1, max(0, x + dx)), min(h - 1, max(0, y + dy))
                        for c in range(3):
                            acc[c] += grid[y][x][c] if False else out[yy][xx][c]
                for c in range(3):
                    tmp[y][x][c] = acc[c] / 9.0
        out = tmp
    return out


def _bilinear(grid, w, h, x, y):
    x = min(max(x, 0.0), w - 1.001)
    y = min(max(y, 0.0), h - 1.001)
    x0, y0 = int(x), int(y)
    fx, fy = x - x0, y - y0
    result = [0.0, 0.0, 0.0]
    for c in range(3):
        top = grid[y0][x0][c] * (1 - fx) + grid[y0][x0 + 1][c] * fx
        bottom = grid[y0 + 1][x0][c] * (1 - fx) + grid[y0 + 1][x0 + 1][c] * fx
        result[c] = top * (1 - fy) + bottom * fy
    return result


